// Bakes the shell's mouse cursors (the arrow and the glove) into src/shell/cursors.css.
//
// The game draws its cursors with roughjs when a run starts. The start screen has no roughjs, so
// the two cursors it needs are rendered here from the same art (src/game/phaser/cursors/art.ts)
// at 32 px and 64 px, and written into the stylesheet as data URLs. Run it after changing that art:
//
//   npm i --no-save playwright-core     (and have a Chromium: npx playwright-core install chromium)
//   node scripts/render-cursors.mjs
//
// The art uses fixed seeds, so the output is the same on every run. Set CHROMIUM_PATH to use a
// browser that is not in Playwright's default location, and PLAYWRIGHT_CORE for the folder of a
// playwright-core that is installed elsewhere.
import { writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'
import { build } from 'vite'

const KINDS = ['arrow', 'glove']
const root = fileURLToPath(new URL('..', import.meta.url))
const out = fileURLToPath(new URL('../src/shell/cursors.css', import.meta.url))

let playwright
try {
  const folder = process.env.PLAYWRIGHT_CORE
  playwright = await import(folder ? pathToFileURL(join(folder, 'index.mjs')).href : 'playwright-core')
} catch {
  throw new Error('playwright-core is missing. Install it with: npm i --no-save playwright-core')
}

// The art module and roughjs as one script for the page.
const result = await build({
  root,
  configFile: false,
  logLevel: 'silent',
  build: {
    write: false,
    lib: { entry: fileURLToPath(new URL('../src/game/phaser/cursors/art.ts', import.meta.url)), formats: ['iife'], name: 'cursorArt' },
  },
})
const bundle = (Array.isArray(result) ? result[0] : result).output[0].code

const browser = await playwright.chromium.launch({ executablePath: process.env.CHROMIUM_PATH || undefined })
const page = await browser.newPage()
await page.setContent('<!doctype html><body></body>')
await page.addScriptTag({ content: bundle })
const images = await page.evaluate((kinds) => {
  const png = (kind, size) => {
    const canvas = document.createElement('canvas')
    canvas.width = canvas.height = size
    globalThis.cursorArt.drawCursor(kind, canvas)
    return canvas.toDataURL('image/png')
  }
  return Object.fromEntries(kinds.map((kind) => [kind, { x1: png(kind, 32), x2: png(kind, 64), ...globalThis.cursorArt.cursorSpec(kind) }]))
}, KINDS)
await browser.close()

const names = { arrow: 'arrow', glove: 'glove' }
const properties = KINDS.map((kind) => `  --arcade-cursor-${names[kind]}-1x: url(${images[kind].x1});\n  --arcade-cursor-${names[kind]}-2x: url(${images[kind].x2});`).join('\n')
const value = (kind, form) => {
  const { hotspot, fallback } = images[kind]
  const at = `${hotspot[0]} ${hotspot[1]}, ${fallback}`
  const one = `var(--arcade-cursor-${names[kind]}-1x)`
  const two = `var(--arcade-cursor-${names[kind]}-2x)`
  return form === 'url' ? `${one} ${at}` : `${form}(${one} 1x, ${two} 2x) ${at}`
}
// The one-pixel image only lets @supports ask whether the browser knows a form of image-set().
const PROBE = 'url(data:image/gif;base64,R0lGODlhAQABAAAAACw=)'
const rules = (form) =>
  [
    `  .arcade-root { cursor: ${value('arrow', form)}; }`,
    `  .arcade-root :is(button, a, [role='button'], summary) { cursor: ${value('glove', form)}; }`,
    `  .arcade-root :is(button, a):disabled { cursor: ${value('arrow', form)}; }`,
  ].join('\n')

const css = `/* Generated by scripts/render-cursors.mjs from src/game/phaser/cursors/art.ts. Do not edit. */

/* The scribble arrow and glove for the start screen, settings and changelog. A mouse only: touch
   screens get no custom cursor. The game puts its own cursor on the canvas and its host element
   (an inline style), which wins over these rules while a run plays. Everything sits under
   .arcade-root, so nothing reaches the page around the arcade. Each image-set form is tried in
   turn, a browser that knows none keeps the plain image. */
@media (hover: hover) and (pointer: fine) {
  .arcade-root {
${properties}
  }
${rules('url')}
  @supports (cursor: -webkit-image-set(${PROBE} 1x) 0 0, auto) {
${rules('-webkit-image-set').replace(/^/gm, '  ')}
  }
  @supports (cursor: image-set(${PROBE} 1x) 0 0, auto) {
${rules('image-set').replace(/^/gm, '  ')}
  }
}
`
writeFileSync(out, css)
console.log(`wrote ${out} (${css.length} bytes)`)
